#!/usr/bin/env python3
"""Render the checked-in Lucide sources. Requires CairoSVG 2.8.2 and Pillow; never runs in game."""
import io,json,math
from pathlib import Path
import cairosvg
from PIL import Image
ROOT=Path(__file__).resolve().parents[1]/'vendor/trs-client'
ART=ROOT/'artwork/lucide'
manifest=json.loads((ART/'manifest.json').read_text());icons=manifest['icons'];cell=manifest['cell'];cols=manifest['columns'];rows=math.ceil(len(icons)/cols)
atlas=Image.new('RGBA',(cols*cell,rows*cell),(0,0,0,0))
for index,(key,name) in enumerate(icons.items()):
 svg=(ART/(name+'.svg')).read_bytes().replace(b'currentColor',b'#ffffff')
 tile=Image.open(io.BytesIO(cairosvg.svg2png(bytestring=svg,output_width=cell,output_height=cell)))
 atlas.paste(tile,(index%cols*cell,index//cols*cell))
tex=ROOT/'common/src/main/resources/assets/trsclient/textures/ui';tex.mkdir(exist_ok=True,parents=True);atlas.save(tex/'icons.png')
(tex/'icons.png.mcmeta').write_text('{"texture":{"blur":true,"clamp":true}}\n')
source='''package dev.theredstonee.trsclient.core.ui;
import java.util.LinkedHashMap;
import java.util.Map;
// Generated by tools/generate_ui_icons.py from pinned, licensed SVG sources.
final class ModernIcons {
    private static final Map<String,Integer> INDEX=new LinkedHashMap<String,Integer>();
    private static TextureRef atlas;
    static {
'''
source+=''.join('        INDEX.put('+json.dumps(k)+','+str(i)+');\n' for i,k in enumerate(icons))
source+='''    }
    static boolean draw(Canvas c,String id,int x,int y,int px,int color) {
        Integer index=INDEX.get(id);
        if(index==null||!c.images()||Textures.store()==null)return false;
        try {
            if(atlas==null)atlas=Textures.store().game("trsclient:textures/ui/icons.png",WIDTH,HEIGHT);
            if(atlas==null)return false;
            c.push();
            try {c.translate(x,y);c.scale(px*8f/64f);c.image(atlas,(index%12)*64,(index/12)*64,64,64,color);}
            finally {c.pop();}
            return true;
        }catch(RuntimeException|LinkageError e){return false;}
    }
}
'''.replace('WIDTH',str(cols*cell)).replace('HEIGHT',str(rows*cell))
(ROOT/'common/src/main/java/dev/theredstonee/trsclient/core/ui/ModernIcons.java').write_text(source)
print('Rendered',len(icons),'icons;',atlas.size)
